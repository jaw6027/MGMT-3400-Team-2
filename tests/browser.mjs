import { chromium, expect } from '@playwright/test';
import { mkdirSync, mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createStore } from '../server/store.js';
import { createApp, attachFrontend } from '../server/app.js';
import { parsePlaces } from '../server/discovery.js';

// All browser tests use an isolated database and a fixture for the public provider.
process.env.NODE_ENV = 'production';
const dir = mkdtempSync(join(tmpdir(), 'vendwell-browser-'));
const store = createStore(join(dir, 'browser.sqlite'));
const fixtures = parsePlaces({ elements: [{ type: 'node', id: 999, lat: 34.682, lon: -118.156, tags: { name: 'Public listing fixture', shop: 'laundry' } }] });
const app = createApp(store, async () => fixtures);
await attachFrontend(app);
const server = app.listen(0, '127.0.0.1');
await new Promise(resolve => server.once('listening', resolve));
const base = `http://127.0.0.1:${server.address().port}`;
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
const errors = [];
let activePage;
mkdirSync('test-results', { recursive: true });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1050 } });
  const page = await context.newPage();
  activePage = page;
  page.on('pageerror', error => { errors.push(error.message); console.error('Browser error:', error.message); });
  await page.goto(base);
  await expect(page.getByText('EXAMPLE WORKSPACE', { exact: true })).toBeVisible();
  await expect(page.locator('.location-card')).toHaveCount(6);
  await page.screenshot({ path: 'test-results/desktop.png', fullPage: true });
  await page.locator('.location-card').filter({ hasText: 'Warehouse break room' }).click();
  await expect(page.getByRole('dialog')).toContainText('Fictional example');
  await expect(page.getByRole('dialog').getByRole('button', { name: 'Update location' })).toHaveCount(0);
  await page.getByRole('button', { name: 'Close dialog' }).click();
  await page.getByRole('button', { name: 'Select Neighborhood laundromat, score 81', exact: true }).focus();
  await page.keyboard.press('Enter');
  await expect(page.getByRole('dialog')).toContainText('Neighborhood laundromat');
  await page.getByRole('button', { name: 'Close dialog' }).click();
  await page.getByRole('button', { name: 'Start scouting', exact: true }).click();
  await expect(page.locator('.location-card')).toHaveCount(0);
  await page.getByRole('button', { name: 'Add location', exact: true }).click();
  await page.getByLabel('Location name *').fill('Field test auto service');
  await page.getByRole('dialog').getByLabel('Location type', { exact: true }).selectOption('Auto service');
  await page.getByLabel('Street address').fill('Example address, Lancaster, CA');
  await page.getByLabel('Latitude (optional)').fill('34.68');
  await page.getByLabel('Longitude (optional)').fill('-118.15');
  await page.getByLabel('Estimated people per day').fill('100');
  await page.getByLabel('Typical time on site (minutes)').fill('60');
  await page.getByLabel('Open hours per day').fill('12');
  await page.getByLabel('Existing vending service').selectOption('none');
  await page.getByLabel('Power & space confirmed').selectOption('yes');
  await page.getByLabel('Student responsible').fill('Student tester');
  await page.getByLabel('Evidence & date').fill('Test fixture — not a real observation.');
  await page.getByRole('dialog').getByRole('button', { name: 'Add location', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.locator('.location-card')).toHaveCount(1);
  await expect(page.locator('.score.small')).toContainText('83');
  await page.reload();
  await expect(page.locator('.location-card')).toHaveCount(1);
  await expect(page.getByText('EXAMPLE WORKSPACE', { exact: true })).toHaveCount(0);
  const teammate = await context.newPage(); await teammate.goto(base);
  await expect(teammate.locator('.location-card')).toHaveCount(1);
  await teammate.close();
  await page.locator('.location-card').click();
  await page.getByRole('button', { name: 'Shortlist', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.locator('nav').getByRole('button', { name: /Shortlist/ }).click();
  await expect(page.locator('.location-card')).toHaveCount(1);
  await page.getByLabel('Search locations').fill('no such location');
  await expect(page.getByText('No matching locations')).toBeVisible();
  await page.getByRole('button', { name: 'Clear filters' }).click();
  await page.locator('.location-card').click();
  await page.getByRole('button', { name: 'Update location', exact: true }).click();
  await page.getByLabel('Outreach stage').selectOption('Contacted');
  await page.getByRole('button', { name: 'Save changes' }).click();
  await page.locator('nav').getByRole('button', { name: 'Outreach', exact: true }).click();
  await expect(page.locator('.pipeline-card')).toHaveCount(1);
  await expect(page.locator('.pipeline-card')).toContainText('Student tester');
  await page.locator('nav').getByRole('button', { name: 'Discover', exact: true }).click();
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export', exact: true }).click();
  const download = await downloadEvent;
  expect(readFileSync(await download.path(), 'utf8')).toContain('Field test auto service');
  await page.getByRole('button', { name: /Search public listings/ }).click();
  await expect(page.getByText('Public listing fixture', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Add lead' }).click();
  await expect(page.getByRole('button', { name: 'Added', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Done', exact: true }).click();
  await expect(page.locator('.location-card')).toHaveCount(2);
  await page.locator('.location-card').filter({ hasText: 'Public listing fixture' }).click();
  await expect(page.getByRole('dialog')).toContainText('Not checked');
  await expect(page.getByRole('dialog')).toContainText('OpenStreetMap listing');
  await page.getByRole('button', { name: 'Close dialog' }).click();
  // Keyboard use and mobile layout at common narrow widths.
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  mobile.on('pageerror', error => errors.push(error.message));
  await mobile.goto(base);
  await expect(mobile.locator('.location-card')).toHaveCount(2);
  expect(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await mobile.screenshot({ path: 'test-results/mobile.png', fullPage: true });
  await mobile.getByRole('button', { name: 'Toggle navigation' }).click();
  await mobile.locator('nav').getByRole('button', { name: /Shortlist/ }).click();
  await expect(mobile.locator('.location-card')).toHaveCount(1);
  await mobile.getByRole('button', { name: 'Add location', exact: true }).click();
  await expect(mobile.getByRole('dialog')).toBeVisible();
  await mobile.getByRole('button', { name: 'Cancel', exact: true }).click();
  await mobile.close();
  // Confirm real deletion and explicit, actionable conflict handling.
  await page.locator('.location-card').filter({ hasText: 'Field test auto service' }).click();
  await page.getByRole('button', { name: 'Update location', exact: true }).click();
  const lead = store.all().find(c => c.name === 'Field test auto service');
  store.update(lead.id, { ...lead, owner: 'Another teammate' });
  await page.getByLabel('Student responsible').fill('Stale overwrite');
  await page.getByRole('button', { name: 'Save changes' }).click();
  await expect(page.getByRole('alert')).toContainText('Another teammate updated');
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.getByRole('button', { name: 'Refresh shared workspace' }).click();
  await page.locator('.location-card').filter({ hasText: 'Field test auto service' }).click();
  await page.getByRole('button', { name: 'Delete location', exact: true }).click();
  await page.getByRole('button', { name: 'Delete permanently', exact: true }).click();
  await expect(page.locator('.location-card')).toHaveCount(1);
  expect(errors).toEqual([]);
  console.log('PASS: desktop and mobile; real database CRUD, persistence, shared edits, conflict handling, shortlist, filters, scoring, outreach, CSV export, and discovery import (provider fixture).');
} catch (error) {
  if (activePage) { await activePage.screenshot({ path: 'test-results/failure.png', fullPage: true }); console.error((await activePage.locator('body').innerText()).slice(-5000)); }
  throw error;
} finally {
  await browser.close();
  await new Promise(resolve => server.close(resolve));
  store.close(); rmSync(dir, { recursive: true, force: true });
}
